import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {batchOutputPosition} from '../lib/batch-output-layout.ts';
import { readWorkspaceSource } from './workspace-source.mjs';
const source={x:100,y:200,w:560,h:340},size={w:370,h:240};
assert.deepEqual(batchOutputPosition(source,size),{x:195,y:640});
const prior={x:195,y:640,w:370,h:240};
assert.deepEqual(batchOutputPosition(source,size,[prior]),{x:195,y:980});
assert.deepEqual(batchOutputPosition(source,size,[{...prior,x:2000}]),{x:195,y:640});
const positions=Array.from({length:11},(_,i)=>batchOutputPosition({...source,x:100+i*660},size));
assert.ok(positions.every(point=>point.y===640));
assert.equal(positions[10].x-positions[0].x,6600);
const unchanged=JSON.stringify({source,size,prior});batchOutputPosition(source,size,[prior]);assert.equal(JSON.stringify({source,size,prior}),unchanged);
const processorSize={w:350,h:310};
const processor={...batchOutputPosition(source,processorSize),...processorSize};
assert.deepEqual(processor,{x:205,y:640,w:350,h:310});
assert.deepEqual(batchOutputPosition(processor,size),{x:195,y:1050});
const expandedProcessor={...processor,h:650};
const final={...batchOutputPosition(expandedProcessor,size),...size};
assert.equal(final.y,1390,'use actual expanded processor height');
assert.deepEqual(batchOutputPosition(source,processorSize,[expandedProcessor,final]),{x:205,y:1730},'repeated batches stack below the existing chain');
assert.equal(processor.x+processor.w/2,source.x+source.w/2);
assert.equal(final.x+final.w/2,source.x+source.w/2);
