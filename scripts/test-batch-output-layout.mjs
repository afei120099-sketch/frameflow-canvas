const batch=ui.slice(ui.indexOf('function BatchVideoActions'),ui.indexOf('function BatchReferenceAction'));
assert.match(batch,/originalBySource.set\(video.id,item.shape.id\)/,'H3 selection anchors to original H3, not a temporary video node');
