import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {rememberVideoPosition,restoreVideoPosition,clearVideoPosition,queueVideoTap,cancelVideoTap} from '../lib/video-playback.ts';
import {isNearViewport} from '../lib/media-activation.ts';
rememberVideoPosition('node:video',{currentTime:3.25});
const restored={currentTime:0,duration:8};restoreVideoPosition('node:video',restored);
assert.equal(restored.currentTime,3.25,'decoder recovery preserves pause position');
clearVideoPosition('node:video');restored.currentTime=0;restoreVideoPosition('node:video',restored);
assert.equal(restored.currentTime,0,'ended video clears resume position');
const viewport={minX:0,minY:0,maxX:100,maxY:100};
assert.equal(isNearViewport({minX:110,minY:0,maxX:120,maxY:10},viewport,0),false);
const source=readFileSync(new URL('../app/canvas-workspace.tsx',import.meta.url),'utf8');
const h3=source.slice(source.indexOf('function H3ResultPreview'),source.indexOf('function H3NodeContent'));
assert.match(h3,/onPlay=\{\(\) => \{ setRequested\(false\); setPlaying\(true\); \}\}/);
assert.match(h3,/clearVideoPosition\(nodeId\+source\)/);
assert.doesNotMatch(h3,/autoPlay/);
assert.match(h3,/selected \|\| requested \|\| playing/);
assert.match(h3,/dragged.current = true; pictureTap\(event.clientX, event.clientY\)/);
assert.match(h3,/!start.controls && !dragged.current && inside/);
assert.match(h3,/aria-label="编辑视频节点"[^\n]+onActivate\(\)/,'editing must remain accessible separately from playback');
assert.doesNotMatch(source,/autoPlay=\{playRequested/);
assert.match(source,/onPlay=\{\(\) => \{ setPlayRequested\(false\); setPlaying\(true\); \}\}/);
const target={isConnected:true};
let singles=0,doubles=0;
const tap=(x=10)=>queueVideoTap(target,x,10,()=>singles++,()=>doubles++);
tap();
assert.equal(singles,0,'single waits for double tap window');
tap();
assert.equal(doubles,1,'double opens settings immediately');
await new Promise(resolve=>setTimeout(resolve,330));
assert.equal(singles,0,'double never toggles playback');
tap();
await new Promise(resolve=>setTimeout(resolve,330));
assert.equal(singles,1,'single toggles exactly once');
tap();cancelVideoTap(target);
await new Promise(resolve=>setTimeout(resolve,330));
assert.equal(singles,1,'unmount/source change cancels pending tap');
console.log('PASS: saved pause position, cleared ended position, no autoplay attribute, consumed intent and drag/control guards');
