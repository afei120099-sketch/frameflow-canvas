// Every link resolves, and the final dependency graph is acyclic.
const visiting=new Set(),done=new Set();
function visit(id) {
  assert.ok(workflow[id],"missing link: "+id);
  assert.ok(!visiting.has(id),"cycle: "+id);
  if(done.has(id))return;
  visiting.add(id);
  for(const value of Object.values(workflow[id].inputs))
    if(Array.isArray(value)&&value.length===2&&typeof value[0]==="string"&&typeof value[1]==="number")visit(value[0]);
  visiting.delete(id);done.add(id);
}
for(const id of Object.keys(workflow))visit(id);
