import assert from 'node:assert/strict';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { buildAssetAiManifest, assetAiMarkdown, assetAiInstructions, selectAssetAiExport } from '../lib/asset-ai-manifest.ts';
import { startInboxServer } from './inbox-server.mjs';
const asset = (id, filename, kind='image') => ({ assetId:id, filename, kind, origin:'imported', storageReference:`image:${id}`, sourceRunId:null, createdAt:1, width:100, height:200 });
const assets = [asset('one','人物.png'), asset('two','办公室.png'), asset('three','其他.wav','audio')];
const roles = [{ displayName:'小林', appearanceAssetIds:['one'], voiceAssetIds:[] }, { displayName:'小王', appearanceAssetIds:[], voiceAssetIds:[] }];
const generated = {...asset('generated', '生成角色.png'), origin:'generated'};
const otherGenerated = {...asset('unbound', '生成帧.png'), origin:'generated'};
roles[0].appearanceAssetIds.push('generated');
const chosen = selectAssetAiExport([...assets, generated, otherGenerated], roles);
assert.deepEqual(chosen.map(item => item.assetId), ['one','two','three','generated']);
const generatedManifest = buildAssetAiManifest(chosen, roles, {}, '2026-11-13T00:00:00Z');
assert.deepEqual(generatedManifest.roles[0].imageIds, ['one','generated']);
assert.equal(generatedManifest.groups.角色.find(row => row.id === 'generated').libraryVisibility, '生成图，素材库里不显示');
assert.match(assetAiMarkdown(generatedManifest), /生成图，素材库里不显示/);
roles[0].appearanceAssetIds.pop();
const data = buildAssetAiManifest(assets, roles, {one:'缩略图/one.jpg'}, '2026-11-13T00:00:00Z');
assert.deepEqual(Object.values(data.groups).map(rows => rows.map(row => row.id)), [['one'],['two'],['three']]);
assert.deepEqual(data.roles.map(role => role.imageIds), [['one'],[]]);
assert.match(assetAiMarkdown(data), /小王：缺图/);
assert.match(assetAiMarkdown(data), /无缩略图/);
assert.match(assetAiInstructions('C:\\test',data), /C:\\test\\_素材库给AI/);
assert.match(assetAiInstructions('C:\\test',data), /共 3 条/);
const root = await mkdtemp(path.join(os.tmpdir(), 'asset-ai-test-'));
const server = await startInboxServer({port:0,root});
try {
 const base = `http://127.0.0.1:${server.address().port}/?`;
 const post = (params, body='test') => fetch(base + new URLSearchParams({op:'asset-ai-write',...params}), {method:'POST',body});
 assert.equal((await post({name:'../素材清单.md'})).status,400);
 assert.equal((await post({name:'../x.jpg',thumbnail:'1'})).status,400);
 assert.equal((await post({name:'素材清单.md'},'清单')).status,200);
 assert.equal(await readFile(path.join(root,'_素材库给AI','素材清单.md'),'utf8'),'清单');
 const jpg = new Uint8Array([255,216,255,217]);
 const params = {name:'00000000-0000-4000-8000-000000000011.jpg',thumbnail:'1'};
 assert.equal((await post(params,jpg)).status,200);
 assert.equal((await (await post(params,jpg)).json()).unchanged,true);
 console.log('asset AI export: manifest, grouping, role-bound generated image, instructions, traversal and unchanged thumbnail passed');
} finally { await new Promise(resolve => server.close(resolve)); await rm(root,{recursive:true,force:true}); }
