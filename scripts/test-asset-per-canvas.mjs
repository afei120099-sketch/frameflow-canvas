import assert from 'node:assert/strict';
import './fake-indexeddb.mjs';
import { configureCanvasLibraryScope, collectLibraryReferences } from '../lib/canvas-library-scope.ts';
import { shapeAssetPages, repairShapeAssetOwnership } from '../lib/canvas-library-migration.ts';
import { registerAsset, listAssets, listAllAssets, assignAssetToCanvases, putMeta, getMeta } from '../lib/production-records.ts';
import { selectAssetAiExport, buildAssetAiManifest, assetAiMarkdown } from '../lib/asset-ai-manifest.ts';
let page='page:A';
const shapes={'page:A':[], 'page:B':[]};
configureCanvasLibraryScope(()=>({pageId:page,references:collectLibraryReferences(shapes[page])}));
const add=src=>registerAsset({kind:'image',origin:'imported',filename:src,mimeType:'image/png',storageReference:src,sourceRunId:null});
const a=await add('image:A'); page='page:B'; const b=await add('image:B');
assert.deepEqual((await listAssets()).map(x=>x.assetId),[b.assetId]);
shapes['page:B'].push({assetId:a.assetId}); page='page:A';
assert.deepEqual((await listAssets()).map(x=>x.assetId),[a.assetId]);
const roles=[{displayName:'角色',appearanceAssetIds:[b.assetId],voiceAssetIds:[]}];
assert.equal((await listAssets()).some(x=>x.assetId===b.assetId),false);
await add('image:B'); assert.ok((await listAssets()).some(x=>x.assetId===b.assetId));
page='page:B'; assert.ok((await listAssets()).some(x=>x.assetId===b.assetId));
const records=[{id:'shape:group',parentId:'page:A',props:{}},{id:'shape:one',parentId:'shape:group',props:{assetId:a.assetId}},{id:'shape:two',parentId:'page:B',props:{roleId:'global-role'}}];
assert.deepEqual(shapeAssetPages([{id:'page:A'},{id:'page:B'}],records,[a,b]).get(a.assetId),['page:A']);
await putMeta('canvas-library-isolation-v1-original-catalogues',{assets:[{...a,canvasPageIds:undefined}],roles:[]});
await assignAssetToCanvases(a.assetId,['page:A','page:B'],true);
const editor={getPages:()=>[{id:'page:A'},{id:'page:B'}],store:{allRecords:()=>records}};
await repairShapeAssetOwnership(editor);
assert.deepEqual((await listAllAssets()).find(x=>x.assetId===a.assetId).canvasPageIds,['page:A']);
assert.deepEqual((await getMeta('canvas-library-isolation-v3-shape-assets-backup')).assets[0].canvasPageIds,['page:A','page:B']);
await repairShapeAssetOwnership(editor);
const chosen=selectAssetAiExport([a,b],roles,new Set([a.assetId]));
assert.equal(chosen.length,2);
const manifest=buildAssetAiManifest(chosen,roles,{},'now','画布甲',new Set([a.assetId]));
assert.match(assetAiMarkdown(manifest),/# 画布甲素材清单/);
assert.equal(manifest.groups.角色[0].libraryVisibility,'其他画布的素材');
configureCanvasLibraryScope();
console.log('PASS: page ownership, shape isolation, role isolation, shared import, v3 backup and idempotence, AI export.');
