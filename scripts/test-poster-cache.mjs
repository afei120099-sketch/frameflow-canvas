import assert from 'node:assert/strict';
import { preparePosterFrame, hasVisiblePosterPixels, capturePoster, getPoster } from '../lib/poster-cache.ts';

const video = { paused: true, currentTime: 0, duration: 5 };
preparePosterFrame(video);
assert.equal(video.currentTime, 0.001);
const playing = { paused: false, currentTime: 0, duration: 5 };
preparePosterFrame(playing);
assert.equal(playing.currentTime, 0, 'Playing media must not be repositioned');
const resumed = { paused: true, currentTime: 2, duration: 5 };
preparePosterFrame(resumed);
assert.equal(resumed.currentTime, 2);
assert.equal(hasVisiblePosterPixels(new Uint8ClampedArray([0, 0, 0, 255])), false);
assert.equal(hasVisiblePosterPixels(new Uint8ClampedArray([40, 12, 9, 255])), true);
let pixels = new Uint8ClampedArray([0, 0, 0, 255]);
globalThis.document = { createElement: () => ({ getContext: () => ({ drawImage() {}, getImageData: () => ({ data: pixels }) }), toDataURL: () => 'data:image/jpeg;base64,opening-frame' }) };
const decoded = { videoWidth: 544, videoHeight: 960, readyState: 1, seeking: false };
assert.equal(capturePoster('test-video', decoded), undefined);
decoded.readyState = 2;
assert.equal(capturePoster('test-video', decoded), undefined);
assert.equal(getPoster('test-video'), undefined, 'Black surface must not poison the cache');
pixels = new Uint8ClampedArray([40, 12, 9, 255]);
decoded.seeking = true;
assert.equal(capturePoster('test-video', decoded), undefined);
decoded.seeking = false;
assert.equal(capturePoster('test-video', decoded), 'data:image/jpeg;base64,opening-frame');
assert.equal(getPoster('test-video'), 'data:image/jpeg;base64,opening-frame');
delete globalThis.document;
console.log('Poster: decoded first frame, black cache rejection, seek and playback safety passed');
