import assert from 'node:assert/strict';
import './fake-indexeddb.mjs';
import {registerAsset} from '../lib/production-records.ts';
import {leftToRight,moveCutClip,canvasCutList,isCuttableVideo} from '../lib/canvas-rough-cut.ts';
import {freezeRoughCut} from '../lib/rough-cut.ts';
import {loadFinalCutList,mutateFinalCutList} from '../lib/final-cut-store.ts';
const sorted=leftToRight([{id:'right',x:900,y:0},{id:'bottom',x:0,y:100},{id:'top',x:0,y:0}]);
assert.deepEqual(sorted.map(s=>s.id),['top','bottom','right']);
await mutateFinalCutList(list=>({...list,title:'旧成片，保留'}));
const before=await loadFinalCutList();
const a=await registerAsset({kind:'video',origin:'imported',filename:'a.mp4',mimeType:'video/mp4',storageReference:'media:a',sourceRunId:null,duration:8});
const b=await registerAsset({kind:'video',origin:'generated',filename:'b.mp4',mimeType:'video/mp4',storageReference:'media:b',sourceRunId:null,duration:5});
const clips=[{nodeId:'shape:a',asset:a,duration:8,inPoint:2,outPoint:4},{nodeId:'shape:b',asset:b,duration:5,inPoint:1,outPoint:4}];
const moved=moveCutClip(clips,1,0);assert.equal(moved[0].nodeId,'shape:b');assert.equal(clips[0].nodeId,'shape:a');
assert.equal(moved[0].inPoint,1);assert.deepEqual(moveCutClip(clips,0,-1),clips);
const {list,rows}=canvasCutList(moved,'selection');const frozen=freezeRoughCut(list,rows);assert.ok(frozen.ok);
assert.deepEqual(frozen.snapshot.clips.map(c=>[c.filename,c.inPoint,c.outPoint]),[['b.mp4',1,4],['a.mp4',2,4]]);
assert.deepEqual(await loadFinalCutList(),before,'old persistent sequence never rewritten');
assert.throws(()=>canvasCutList([{...clips[0],inPoint:5,outPoint:4}],'s'),/第1段/);
assert.throws(()=>canvasCutList([{...clips[0],outPoint:9}],'s'),/超出/);
assert.throws(()=>canvasCutList([{...clips[0],inPoint:NaN}],'s'),/入点/);
assert.equal(isCuttableVideo({type:'h3-node',props:{shotId:'x'}}),true);
assert.equal(isCuttableVideo({type:'h3-node',props:{inheritedVideo:{src:'media:x'}}}),true);
assert.equal(isCuttableVideo({type:'h3-node',props:{}}),false);
assert.equal(isCuttableVideo({type:'image-node',props:{src:'image:x'}}),false);
assert.equal(isCuttableVideo({type:'video-node',props:{src:'media:x'}}),true);
console.log('PASS canvas rough cut: left-to-right stable order, reordering keeps trims, validation, snapshot, old data preserved, video selection');
