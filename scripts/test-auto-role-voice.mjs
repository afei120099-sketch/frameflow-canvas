import assert from 'node:assert/strict';
import { resolveH3Speaker, hasPromptDialogue, readAutoVoicePreference, AUTO_VOICE_KEY } from '../lib/h3-speaker-policy.ts';
import { parseShotQueue, shotQueueWarnings, shotQueueH3Props } from '../lib/shot-queue.ts';
const prompt='Host says <d>[Chinese] 给我一分钟。</d>';
const input={prompt,roleIds:['host','guest'],soundMode:'av'};
assert.equal(resolveH3Speaker(input).voiceRoleId,'host');
assert.equal(resolveH3Speaker(input).automatic,true);
assert.equal(resolveH3Speaker({...input,voiceRoleId:'guest'}).voiceRoleId,'guest');
assert.equal(resolveH3Speaker({...input,roleIds:[]}).errors.length,1);
assert.equal(resolveH3Speaker({...input,autoVoiceEnabled:false}).errors.length,1);
assert.equal(resolveH3Speaker({...input,voiceRoleId:'guest',autoVoiceEnabled:false}).voiceRoleId,'guest');
assert.deepEqual(resolveH3Speaker({...input,autoVoiceDisabled:true}).errors,[]);
assert.equal(resolveH3Speaker({...input,autoVoiceDisabled:true,voiceRoleId:'host'}).voiceRoleId,undefined);
assert.equal(resolveH3Speaker({...input,prompt:'A landscape'}).voiceRoleId,undefined);
assert.equal(hasPromptDialogue('<d>[Chinese]  </d>'),false);
assert.equal(hasPromptDialogue('<D>[English] Hello</D>'),true);
assert.match(resolveH3Speaker({...input,soundMode:'silent'}).errors.join(),/av/);
const shot={title:'对白镜',prompt,roleIds:['host','guest'],sceneAssetIds:[],seconds:8,aspect:'16:9',soundMode:'av'};
const raw=(value)=>JSON.stringify({version:'shot-queue-v1',title:'测试',chapters:[{title:'章节',shots:[value]}]});
const queue=parseShotQueue(raw(shot));
assert.equal(queue.chapters[0].shots[0].voiceRoleId,'host');
assert.ok(shotQueueWarnings(queue).some(w=>/自动使用/.test(w)));
assert.equal(shotQueueH3Props(queue.chapters[0].shots[0],{scenes:[],appearances:[],pictures:[]}).voiceRoleId,'host');
assert.equal(parseShotQueue(raw({...shot,voiceRoleId:'guest'})).chapters[0].shots[0].voiceRoleId,'guest');
assert.throws(()=>parseShotQueue(raw({...shot,roleIds:[]})),/对白镜.*没有说话角色/);
assert.throws(()=>parseShotQueue(raw(shot),false),/没有说话角色/);
const disabled=parseShotQueue(raw({...shot,autoVoiceDisabled:true}));
assert.equal(disabled.chapters[0].shots[0].voiceRoleId,undefined);
assert.equal(shotQueueH3Props(disabled.chapters[0].shots[0],{scenes:[],appearances:[],pictures:[]}).autoVoiceDisabled,true);
assert.equal(parseShotQueue(raw({...shot,prompt:'A landscape',roleIds:[]})).chapters[0].shots[0].voiceRoleId,undefined);
assert.equal(parseShotQueue(JSON.stringify(queue)).chapters[0].shots[0].voiceRoleId,'host');
globalThis.window={localStorage:{getItem:key=>key===AUTO_VOICE_KEY?'false':null}};
assert.equal(readAutoVoicePreference(),false);
assert.throws(()=>parseShotQueue(raw(shot)),/没有说话角色/);
delete globalThis.window;
console.log('PASS automatic speaker, explicit selection/opt-out, dialogue blocking, queue inference/warnings/compatibility, global preference');
