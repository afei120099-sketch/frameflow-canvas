// Isolated browser context. All ComfyUI HTTP requests go to a disposable fake; never real GPU.
import assert from "node:assert/strict";
import { pathToFileURL } from "node:url";
import { startFakeComfy } from "./fake-comfyui.mjs";
const [playwrightEntry, executablePath, baseUrl = "http://localhost:5173/"] = process.argv.slice(2);
const { chromium } = await import(pathToFileURL(playwrightEntry).href);
const fake = await startFakeComfy({ files: [{ seed: 1, path: ".claude/artifacts/v1-final/h3.mp4" }], runMs: 100 });
const browser = await chromium.launch({ executablePath, headless: true });
const page = await browser.newPage({ viewport: { width: 1900, height: 1900 } });
const errors = [];
let thermalBlocked = false;
page.on("pageerror", error => errors.push(error.message));
await page.route("**/comfyui/**", async route => {
  const url = new URL(route.request().url());
  if (!url.pathname.startsWith("/comfyui/")) return route.continue();
  if (thermalBlocked && url.pathname === "/comfyui/prompt") return route.fulfill({ status: 503, json: { error: "GPU 温度保护已锁定（模拟）" } });
  await route.fulfill({ response: await route.fetch({ url: `${fake.url}${url.pathname.replace(/^\/comfyui/, "")}${url.search}` }) });
});
await page.routeWebSocket(/(?:\/comfyui\/ws|:8188\/ws)/, socket => socket.close());
try {
  await page.goto(baseUrl);
  await page.getByRole("button", { name: "添加素材或节点" }).waitFor();
  await page.mouse.dblclick(750, 220);
  await page.locator(".canvas-quick-menu").getByRole("button", { name: "H3 视频", exact: true }).click();
  const node = page.locator('.tl-shape[data-shape-type="h3-node"]');
  const dock = page.getByRole("region", { name: "视频创作面板" });
  const count = dock.getByLabel("生成次数", { exact: true });
  assert.equal(await count.inputValue(), "1");
  await count.selectOption("3");
  await dock.locator(".prompt-field textarea").fill("固定机位，树叶随微风轻轻晃动。无对白。");
  assert.equal(await count.inputValue(), "3");
  // tldraw's disk persistence is debounced; wait for the ordinary autosave before reload.
  await page.waitForTimeout(1800);
  await page.reload();
  await node.locator(".h3-preview").click();
  await count.waitFor(); assert.equal(await count.inputValue(), "3");
  await dock.getByRole("button", { name: "生成 3 次", exact: true }).click();
  await node.locator(".h3-candidates-link").filter({ hasText: "候选 3" }).waitFor({ timeout: 90000 });
  assert.equal(fake.state.promptPosts, 3);
  assert.equal(fake.state.maxConcurrent, 1);
  assert.equal(new Set(fake.state.prompts.map(p => p.id)).size, 3);
  assert.equal(new Set(fake.state.prompts.map(p => p.seed)).size, 3);
  const candidateSelect = dock.getByRole("combobox", { name: "当前候选" });
  assert.equal(await candidateSelect.locator("option").count(), 3);
  const lastSource = await node.locator(".h3-preview").getAttribute("data-result-source");
  assert(lastSource, "completed candidate is shown on the original H3 node");
  const firstId = await candidateSelect.locator("option").first().getAttribute("value");
  await candidateSelect.selectOption(firstId);
  const firstSource = await node.locator(".h3-preview").getAttribute("data-result-source");
  assert.notEqual(firstSource, lastSource, "candidate switching changes the inline preview without generating");
  await node.getByRole("button", { name: "播放当前候选" }).click();
  await page.waitForFunction(() => { const video = document.querySelector('.h3-preview video'); return video && video.videoWidth > 0; });
  await page.waitForFunction(() => { const preview = document.querySelector('.h3-preview'); const video = preview?.querySelector('video'); return video?.videoWidth > 0 && Math.abs(preview.clientWidth / preview.clientHeight - video.videoWidth / video.videoHeight) < 0.01; });
  assert.equal(fake.state.promptPosts, 3, "playback and candidate switching never submit generation");
  await dock.getByRole("button", { name: "☆ 采用", exact: true }).click();
  await dock.getByRole("button", { name: "★ 已采用", exact: true }).waitFor();
  await node.locator(".h3-preview video").evaluate(video => video.pause());
  await page.screenshot({ path: ".claude/generation-count-browser.png" });
  await node.locator(".h3-candidates-link").click();
  await page.locator('.shot-candidate-list > button').first().waitFor();
  assert.equal(await page.locator('.shot-candidate-list > button').count(), 3);
  await page.getByRole("button", { name: "关闭候选结果" }).click();
  await page.waitForTimeout(1800);
  await page.reload();
  await node.locator(".h3-preview").waitFor();
  await dock.getByRole("button", { name: "★ 已采用", exact: true }).waitFor();
  assert.equal(await node.locator(".h3-preview").getAttribute("data-result-source"), firstSource, "adopted inline result survives refresh");
  assert.equal(await candidateSelect.inputValue(), firstId);
  await node.locator(".h3-preview").click();
  fake.state.runMs = 8000;
  await dock.getByRole("button", { name: "生成 3 次", exact: true }).click();
  const until = Date.now() + 15000;
  while (fake.state.promptPosts < 4 && Date.now() < until) await new Promise(r => setTimeout(r, 25));
  assert.equal(fake.state.promptPosts, 4);
  await dock.getByRole("button", { name: "取消", exact: true }).click();
  await dock.getByRole("button", { name: "生成 3 次", exact: true }).waitFor();
  await page.waitForTimeout(1200);
  assert.equal(fake.state.promptPosts, 4, "cancelling must stop all remaining repetitions");
  assert.match(await node.locator('.h3-candidates-link').innerText(), /候选 3/);
  assert.equal(await node.locator(".h3-preview").getAttribute("data-result-source"), firstSource, "cancel does not replace the adopted preview");
  fake.state.runMs = 100; fake.state.failures.push("模拟执行失败");
  await dock.getByRole("button", { name: "生成 3 次", exact: true }).click();
  await dock.getByText(/模拟执行失败/).first().waitFor();
  await page.waitForTimeout(1200);
  assert.equal(fake.state.promptPosts, 5, "execution failure must not submit the next candidate");
  thermalBlocked = true;
  await dock.getByRole("button", { name: "生成 3 次", exact: true }).click();
  await dock.getByText(/GPU 温度保护已锁定/).first().waitFor();
  await page.waitForTimeout(1200);
  assert.equal(fake.state.promptPosts, 5, "thermal rejection must not reach the fake GPU queue");
  assert.match(await node.locator('.h3-candidates-link').innerText(), /候选 3/);
  assert.deepEqual(errors, []);
  console.log("PASS: default/persisted count, serial execution, unique IDs/seeds, three saved candidates, cancel/failure/thermal stop remaining submissions and preserve results; no GPU");
} catch (cause) { console.error(errors); console.error((await page.locator("body").innerText()).slice(0, 1600)); await page.screenshot({ path: ".claude/generation-count-failure.png" }); throw cause; }
finally { await browser.close(); await fake.close(); }
