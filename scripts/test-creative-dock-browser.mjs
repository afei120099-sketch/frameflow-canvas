// Disposable browser data on the isolated smoke server. Never submit a GPU job.
import assert from "node:assert/strict";
import { pathToFileURL } from "node:url";
const [entry, executablePath, baseUrl="http://127.0.0.1:5180/"] = process.argv.slice(2);
const { chromium } = await import(pathToFileURL(entry).href);
const browser = await chromium.launch({ executablePath, headless:true });
const page = await browser.newPage({ viewport:{width:1600,height:1000} });
const errors=[];
page.on("pageerror", e=>errors.push(e.message));
await page.route("**/comfyui/prompt", route=>{ throw new Error("UI test must not submit GPU tasks: "+route.request().url()); });
await page.routeWebSocket(/:8188\/ws/, socket=>socket.close());
try {
  await page.goto(baseUrl);
  await page.getByRole("button", {name:"添加素材或节点"}).waitFor();
  await page.mouse.dblclick(950,430);
  await page.locator(".canvas-quick-menu").getByRole("button",{name:"H3 视频",exact:true}).click();
  const dock=page.getByRole("region",{name:"视频创作面板"});
  const h3=page.locator('.tl-shape[data-shape-type="h3-node"]').first();
  await dock.waitFor();
  assert.equal(await h3.getByRole("region", {name:"视频创作面板"}).count(),1,"composer lives inside its own video node");
  assert.equal(await dock.evaluate(el=>getComputedStyle(el).position),"relative","no global fixed-bottom dock");
  assert.equal(await dock.locator(".storyboard-slot-grid > *").count(),5);
  assert.equal(await dock.locator(".duration-control").isVisible(),false);
  const prompt=dock.locator(".prompt-field textarea");
  await prompt.fill("固定机位，人物缓慢转身。中文 / English。");
  assert.equal(await prompt.inputValue(),"固定机位，人物缓慢转身。中文 / English。");
  await dock.getByRole("button",{name:/H3 ·/}).click();
  const settings=page.getByRole("dialog",{name:"视频参数"});
  await settings.locator(".duration-control").waitFor();
  assert.equal(await page.locator(".h3-settings-backdrop").count(),0,"popover never uses a blocking backdrop");
  assert((await settings.boundingBox()).width <= 360,"small anchored panel");
  await settings.locator(".duration-control input[type=number]").fill("7");
  await settings.locator(".duration-control input[type=number]").press("Tab");
  await page.mouse.click(1500,100);
  await settings.waitFor({state:"detached"});
  await dock.getByRole("button",{name:"多参考",exact:true}).click();
  await dock.getByRole("button",{name:"+ 参考图",exact:true}).waitFor();
  await dock.getByRole("button",{name:"顺序图片",exact:true}).click();
  await dock.locator('[data-frame-role="first"]').click();
  const picker=page.getByRole("dialog",{name:"选择首帧图片"});
  const chooser=page.waitForEvent("filechooser");
  await picker.getByRole("button",{name:"上传新图片",exact:true}).click();
  await (await chooser).setFiles(".claude/artifacts/v1-final/first.png");
  await picker.waitFor({state:"hidden"});
  await h3.locator(".h3-preview").click();
  await dock.getByAltText("连接的首帧").waitFor();
  await page.waitForFunction(()=>{ const p=document.querySelector(".h3-preview"), img=p?.querySelector("img"); return img?.naturalWidth > 0 && Math.abs(p.clientWidth / p.clientHeight - img.naturalWidth / img.naturalHeight)<0.01; });
  assert.equal(await page.locator(".workflow-curve").count(),1);
  assert.match(await page.locator(".workflow-curve").getAttribute("d"),/ C/);
  await dock.getByRole("button",{name:"文本",exact:true}).click();
  assert.equal(await page.locator('.tl-shape[data-shape-type="image-node"]').count(),1,"changing input view never deletes media");
  assert.match(await dock.locator(".creative-dock-header").innerText(),/首帧/);
  await dock.getByRole("button",{name:"顺序图片",exact:true}).click();
  await dock.getByRole("button",{name:"展开图片预览"}).click();
  assert.equal(await dock.getByRole("button",{name:"展开图片预览"}).getAttribute("aria-expanded"),"true");
  const bounds=await dock.boundingBox();
  assert(bounds.height < 500,"composer remains compact with a portrait preview");
  await dock.getByRole("button",{name:"展开图片预览"}).click();
  await page.screenshot({path:".claude/creative-dock-browser.png"});
  await dock.getByRole("button",{name:"多参考",exact:true}).click();
  await dock.getByAltText("第一参考图").waitFor();
  const referenceChooser=page.waitForEvent("filechooser");
  await dock.getByRole("button",{name:"+ 参考图",exact:true}).click();
  await (await referenceChooser).setFiles(".claude/artifacts/v1-final/first.png");
  await dock.locator(".creative-reference-strip .reference-item").waitFor();
  await page.waitForFunction(()=>document.querySelector('.h3-inline-composer [data-task-mode]')?.getAttribute('data-task-mode') === 'ref2va');
  await dock.getByRole("button",{name:/声音 \/ 视频 \/ 角色/}).click();
  await settings.getByRole("button",{name:"专业",exact:true}).click();
  await settings.getByRole("button",{name:/专业参数/}).click();
  assert.equal(await settings.getByLabel("实际 Steps",{exact:true}).inputValue(),"4","multi-reference retains its frozen Turbo parameters");
  const settingsBounds=await settings.boundingBox();
  assert(settingsBounds.y>=0 && settingsBounds.y+settingsBounds.height<=1000);
  assert.equal(await settings.locator('.h3-settings-body').evaluate(el=>getComputedStyle(el).overflowY),"auto");
  await page.screenshot({path:".claude/creative-parameters-browser.png"});
  await settings.getByRole("button",{name:"关闭视频参数"}).click();
  await page.mouse.click(1500,100);
  assert.equal(await dock.isVisible(),true,"preview and controls remain one card after deselection");
  const image=page.locator('.tl-shape[data-shape-type="image-node"]');
  const box=await image.boundingBox();
  await page.mouse.move(box.x+box.width/2,box.y+box.height/2);
  await page.waitForTimeout(250);
  const ports=image.locator(".workflow-port");
  assert.equal(await ports.count(),2);
  assert.deepEqual(await ports.evaluateAll(ps=>ps.map(p=>getComputedStyle(p).opacity)),["1","1"]);
  await page.mouse.move(1500,100);
  await page.waitForTimeout(250);
  assert.deepEqual(await ports.evaluateAll(ps=>ps.map(p=>getComputedStyle(p).opacity)),["0","0"]);
  await page.mouse.move(box.x+box.width/2,box.y+box.height/2);
  await image.locator(".workflow-port:not(.workflow-input-port)").click();
  await page.waitForFunction(()=>document.querySelectorAll('.tl-shape[data-shape-type="h3-node"]').length===2);
  assert.equal(await page.locator(".workflow-curve").count(),2,"normal image-to-H3 path remains bound");
  assert.deepEqual(errors,[]);
  console.log("PASS: integrated node preview/composer, compact five slots, settings popup, prompt/duration, multi-reference view, upload, curves, non-destructive view switching, picture expand/collapse and hover +/-; no GPU");
} catch(e) { console.error(errors); await page.screenshot({path:".claude/creative-dock-failure.png"}); throw e; }
finally { await browser.close(); }
